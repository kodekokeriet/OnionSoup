#!/usr/bin/env python3
"""Renders a monospace TTF into an 8x12 bitmap font (ASCII 32-126 + a few extras) in src/font.h."""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
out = sys.argv[2] if len(sys.argv) > 2 else "src/font.h"
W, H = 8, 12
font = ImageFont.truetype(ttf, 10)
EXTRA = "æøåÆØÅ"
chars = [chr(c) for c in range(32, 127)] + list(EXTRA)
rows = []
for ch in chars:
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((0, -1), ch, font=font, fill=255)
    rows.append([sum((1 << (7 - x)) for x in range(W) if img.getpixel((x, y)) > 60) for y in range(H)])
with open(out, "w") as f:
    f.write("/* Generated by tools/gen_font.py - do not edit by hand. */\n")
    f.write("#define FONT_W %d\n#define FONT_H %d\n#define FONT_N %d\nstatic const unsigned char font8x12[FONT_N][%d] = {\n" % (W, H, len(chars), H))
    for ch, r in zip(chars, rows):
        f.write("  {%s}, /* U+%04X */\n" % (",".join("0x%02x" % b for b in r), ord(ch)))
    f.write("};\n")
